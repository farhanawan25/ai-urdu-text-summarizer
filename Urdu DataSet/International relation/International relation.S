واشنگٹن — 
یہ جون 2003 ہے اور امریکی دارالحکومت واشنگٹن سے باہر کیمپ ڈیوڈ کا تاریخی مقام، جہاں اس وقت کے امریکہ کے صدر جارج بش پاکستان کے فوجی صدر پرویز مشرف کا بھرپور استقبال کرتے ہوئے اسلام آباد کے لیے تین ارب ڈالرز کے امدادی پیکج کا اعلان کرتے ہیں۔

کچھ ماہ بعد پاکستان کو امریکہ کا میجر نان نیٹو اتحادی کا درجہ دیا جاتا ہے جس سے پاکستان کے لیے امریکی دفاعی امداد کی راہ ہموار ہوتی ہے۔ پاکستان پہلے ہی نو ستمبر 2001 کے دہشت گردی کے حملوں کے بعد امریکہ کے افغانستان میں فوجی آپریشن کے لیے انتہائی اہم راہداری مہیا کر چکا ہے اور اس نے سینکڑوں القاعدہ عسکریت پسندوں کو پکڑ کر امریکہ کے حوالے بھی کردیا ہے۔

دونوں ممالک میں 1990 کی دہائی میں پیدا ہونے والی دوری کے تناظر میں کیمپ ڈیوڈ میں گہرے ہوتے دو طرفہ تعاون کو سفارتی سطح پر حالیہ تاریخ میں پاک امریکہ تعلقات کا نقطہ عروج کہا جاتا ہے۔لیکن اس پیش رفت کے چند ہی سالوں میں پاکستان اور امریکہ کے بظاہر وسیع تر ہوتے تعلقات میں اختلافات کی نمایاں خلیج نظر آنے لگتی ہے اور دونوں اطراف سے مشرف دور کے سن 2008 میں خاتمے سے پہلے ہی ناکافی تعاون کی شکایات اور وعدے پورے نہ کرنے کے الزامات کا سلسلہ جاری ہو جاتا ہے۔

دو عشرے قبل استوار کیے گئے پرویز مشرف کے دور میں پاکستان کے امریکہ کے ساتھ تعاون کے موضوع پر آج کے حالات میں بھی مختلف آراپائی جاتی ہیں۔ لیکن مبصرین کے نزدیک اس وقت سب سے بڑا سوال یہ ہے کہ مشرف دور کے اختلافات کی پرچھائیں کب تک پاک امریکہ تعلقات پر پڑتی رہے گی اور کیا آج کے مختلف ماحول میں اس وقت سر اٹھانے والے گھمبیر مسائل اس کے ہوتے ہوئے تعلقات کو از سر نو تعمیر کر سکتے ہیں؟

واشنگٹن کے دی مڈل ایسٹ انسٹی ٹیوٹ کے پاکستان اور افغانستان شعبہ کے ڈائریکٹر مارون وائن بام کہتے ہیں امریکہ کے لیے نائن الیون کے فوراً بعد پاکستا ن کا تعاون حاصل کرناایک بڑی کامیابی تھی جبکہ دوسری جانب پرویز مشرف کے امریکہ کے ساتھ تعاون کے فیصلے کو عوامی قبولیت حاصل نہیں تھی۔

