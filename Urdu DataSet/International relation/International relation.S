اس سلسلے میں انہوں نے کہا کہ پاکستان کہا کرتا تھا کہ امریکہ ایک دن اس خطے سے واپس چلا جائے گا اور اسے افغانستان کے اندر بننے والی صورت حال سے نمٹنے کے لیے پشتون آبادی کی حمایت کی ضرورت ہوگی، اور ایسا ہی ہوا۔ وہ کہتی ہیں یہی بات پاکستان کی حقانی گروپ کو پناہ گاہیں دینے کی دوغلی پالیسی پر بھی روشنی ڈالتی ہے۔

انہوں نے پاکستان پر تنقید کرتے ہوئے کہا کہ کئی مواقع میسرہونے کے باوجود اسلام آباد نے وہ اقتصادی اصلاحات نہیں اپنائیں جن کی اسے ترقی کے لیے اشد ضرورت ہے اور یہی وجہ ہے کہ پاکستان ایک آزاد خارجہ پالیسی نہیں بنا پاتا۔ جب آپ اپنے خرچوں کے بل اد ا نہیں کر سکتے تو آزاد پالیسی کیسے اختیار کرسکتے ہیں؟

رابن رافیل کے مطابق تقریباً تمام بین الااقوامی تعلقات کے کچھ منفی اور کچھ مثبت پہلوہوتے ہیں اور مشرف کے وقت کی پالیسیوں کے باوجود آجکل کے نئے چیلنجز کے دور میں جبکہ امریکہ پاکستان کے قریبی حلیف چین پر نظریں جمائے ہوئےہے ، پاکستان اور امریکہ اپنے باہمی تعلقات کے مثبت پہلوؤں کو آگے بڑھا کر دوطرفہ تعاون کو فروغ دے سکتے ہیں۔ اس ضمن میں حالیہ کوششیں حوصلہ افزا اور اہم ہیں کیونکہ پاکستان کی اس خطے میں اہمیت کبھی کم نہیں ہو گی۔