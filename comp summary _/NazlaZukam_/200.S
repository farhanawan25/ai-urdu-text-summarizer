**نزلے کی صورت میں چند طریقے استعمال کیے جا سکتے ہیں:**

1. **زیادہ پانی پیئیں**: نزلے کی علامات کو ختم کرنے اور سانس کی نالی کو کشادہ کرنے کے لئے زیادہ سے زیادہ پانی پیئیں۔

2. **اچھی نیند لیں**: رات کو گہری نیند سے آپ کی قوتِ مدافعت میں اضافہ ہوتا ہے، جس سے وائرس بے اثر ہوجاتے ہیں۔

3. **نمک والے پانی سے غرغرہ کریں**: یہ طریقہ حلق کی سوزش کو ختم کرتا ہے اور وائرس اور بیکٹیریا کو ختم کرتا ہے۔

4. **معالج سے مشورہ کریں**: معالج سے مشورہ لیں اور دوائیں استعمال کریں۔ یہ طریقہ نزلے کے اثرات کو کم کرتا ہے۔